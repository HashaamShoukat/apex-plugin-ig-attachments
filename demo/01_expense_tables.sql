-- IG Attachments example: expense claims and their own attachments table (Storage = My Table).
-- Run in the application's parsing schema after dist/install.sql.
create table expenses (
    id           number generated by default on null as identity primary key,
    expense_date date          default trunc(sysdate) not null,
    category     varchar2(30)  not null,
    description  varchar2(255) not null,
    amount       number(12,2)  not null,
    owner_name   varchar2(255) not null
);

create table expense_files (
    file_id          number generated by default on null as identity primary key,
    expense_id       number not null references expenses (id) on delete cascade,
    file_name        varchar2(255 char) not null,
    mime_type        varchar2(100),
    file_size        number,
    content          blob not null,
    -- Extra Fields of the column
    document_type    varchar2(200),
    remarks          varchar2(1000),
    expense_category varchar2(30)
);
create index expense_files_expense on expense_files (expense_id);

-- Optional Authorization Function of the column. The grid already decides who sees, adds, changes
-- and removes files; this adds a rule: claims older than 90 days can be read but not changed.
create or replace function expense_attachment_rule (
    p_key       in varchar2,
    p_operation in varchar2   -- READ, CREATE (key null), WRITE, DELETE
) return boolean
is
    l_count number;
begin
    if p_operation in ('READ', 'CREATE') then
        return true;
    end if;
    select count(*) into l_count from expenses
     where id = to_number(p_key)
       and expense_date >= trunc(sysdate) - 90;
    return l_count = 1;
end;
